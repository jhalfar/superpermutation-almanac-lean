"""gen_tabok7.py: writes the checks of the tables of K7/Tab.lean by the kernel.

    python gen_tabok7.py [OUT] [CHUNK]

  K7/TabEnc.lean        the coding `enc` (the Lehmer rank) and `all_of_chunks`
  K7/TabOK/C_*.lean     one check over the 5,040 words (or the 5,040 permutations of 1..7) each, evaluated in
                        pieces of CHUNK (default 252) words, so that no evaluation needs much memory
  K7/TabOK.lean         the consequences (from tools/tabok7_tail.lean)

The checks and the consequences are those of K6/TabOK.lean of the 872 batch for 7 symbols, with one change:
the coding `enc w` is the Lehmer rank of `w` (computed, not looked up), so that every check is linear in the
number of words.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(HERE)
CH = int(sys.argv[2]) if len(sys.argv) > 2 else 252
N = 5040
assert N % CH == 0
NC = N // CH
ID = '[1, 2, 3, 4, 5, 6, 7]'

CHECKS = [
    ('idx', '(List.range 5040)', 'fun i => enc (pw i) == i'),
    ('all', f'(List.permutations\' {ID})', 'fun w => decide (enc w < 5040) && pw (enc w) == w'),
    ('rot', '(List.range 5040)', 'fun i =>\n    (pw i).rotate (rot i) == pw (rep (ci i)) && decide (rep (ci i) < 5040)'),
    ('ci_rot', '(List.range 5040)', 'fun i => ci (enc ((pw i).rotate 1)) == ci i'),
    ('nx', '(List.range 5040)', 'fun i =>\n    pw (nx i) == doorW ((pw i).rotate 6) && decide (nx i < 5040)'),
    ('s3', '(List.range 5040)', 'fun i =>\n    (((pw i).rotate 6).take 3).permutations\'.all (fun t =>\n'
                                '      (List.range 7).any (fun s => (((pw i).rotate 6).drop 3 ++ t).rotate s == pw i) ||\n'
                                '      (List.range 5).any (fun j => pw (s3 i j) == ((pw i).rotate 6).drop 3 ++ t && decide (s3 i j < 5040)))'),
    ('perm', '(List.range 5040)', f'fun i => (pw i).isPerm {ID}'),
]

ENC = '''import Mathlib.Data.List.Permutation
import Mathlib.Data.List.Rotate
import Mathlib.Data.Nat.Factorial.Basic
import LowerBounds.SSound
import K7.Engine

-- Generated by `tools/gen_tabok7.py`.  Changed for the 5,898 batch: from K6/TabOK.lean of the 872 batch, for 7
-- symbols, with `enc` the Lehmer rank instead of the index in a list.

/-!
# The coding of the words of the search on 7 symbols

`enc w` is the Lehmer rank of the word `w` (its index in the lexicographic order of the permutations; `TP`
lists the words in that order).  `K7/TabOK/` checks the tables against the words, `K7/TabOK.lean` draws the
consequences.
-/

namespace K7

open SuperpermLowerBounds SuperpermLowerBounds.S

/-- The Lehmer rank of a word: for each letter, the number of smaller letters after it, times the
factorial of the number of letters after it. -/
def enc : List ℕ → ℕ
  | [] => 0
  | a :: t => t.countP (fun b => decide (b < a)) * Nat.factorial t.length + enc t

/-- A check over a list, from checks over its pieces of `k` elements. -/
theorem all_of_chunks {α : Type} (g : α → Bool) (k : ℕ) :
    ∀ (m : ℕ) (L : List α), L.length ≤ m * k →
      (∀ j, j < m → ((L.drop (j * k)).take k).all g = true) → L.all g = true
  | 0, L, hl, _ => by
    have e : L = [] := List.eq_nil_of_length_eq_zero (by simpa using hl)
    subst e
    rfl
  | m + 1, L, hl, h => by
    rw [← List.take_append_drop k L, List.all_append, Bool.and_eq_true]
    refine ⟨by simpa using h 0 (by omega), ?_⟩
    refine all_of_chunks g k m (L.drop k) (by simp; rw [Nat.add_mul] at hl; omega) (fun j hj => ?_)
    have := h (j + 1) (by omega)
    rwa [List.drop_drop, show k + j * k = (j + 1) * k by rw [Nat.add_mul]; omega]

end K7
'''

TABOK_HEAD = '''
-- Generated by `tools/gen_tabok7.py`.  Changed for the 5,898 batch: K6/TabOK.lean of the 872 batch for 7
-- symbols; the checks are in K7/TabOK/ (5,040 words in pieces of {ch}).

/-!
# The tables of the search on 7 symbols mean what they say

Every fact below is checked against the words by `decide +kernel` (the kernel computes the tables and the
words, `K7/TabOK/`) and then carried to all permutation words:

* `enc_pw`, `pw_enc`: `enc` and `pw` are inverse on permutation words;
* `ci_eq_iff`: two permutation words have the same class index iff they are rotations of each other;
* `nx_enc`: `nx` is the door of the exit (`DoorEq`);
* `s3_enc`: a word of another class that the exit of `u` overlaps in 3 letters is one of `s3 (enc u) j`.
-/

namespace K7

open SuperpermLowerBounds SuperpermLowerBounds.S

theorem chk_id : pw 0 = {ident} := by decide +kernel

'''


def write(path, txt):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(txt)


def main():
    write(os.path.join(OUT, 'K7', 'TabEnc.lean'), ENC)
    for name, lst, fn in CHECKS:
        F = ['import Mathlib.Tactic.IntervalCases', 'import K7.TabEnc', '',
             f'-- Generated by `tools/gen_tabok7.py`: one check of K7/TabOK.lean, in pieces of {CH} words.', '',
             'namespace K7', '', 'open SuperpermLowerBounds SuperpermLowerBounds.S', '']
        for j in range(NC):
            F.append('set_option maxRecDepth 100000 in')
            F.append(f'theorem chk_{name}_{j} : (({lst}.drop ({j} * {CH})).take {CH}).all')
            F.append(f'    ({fn}) = true := by')
            F.append('  decide +kernel')
            F.append('')
        F.append(f'theorem chk_{name} : {lst}.all ({fn}) = true :=')
        F.append(f'  all_of_chunks _ {CH} {NC} _ (by decide +kernel) (by')
        F.append('    intro j hj')
        F.append('    interval_cases j')
        F.append('    exacts [' + ', '.join(f'chk_{name}_{j}' for j in range(NC)) + '])')
        F += ['', 'end K7', '']
        write(os.path.join(OUT, 'K7', 'TabOK', f'C_{name}.lean'), '\n'.join(F))
    T = ''.join(f'import K7.TabOK.C_{c[0]}\n' for c in CHECKS)
    T += TABOK_HEAD.format(ch=CH, ident=ID)
    T += open(os.path.join(HERE, 'tabok7_tail.lean'), encoding='utf-8').read()
    write(os.path.join(OUT, 'K7', 'TabOK.lean'), T)


main()
