"""gen_arith7.py: writes K7/ArithTab.lean, the certificate of the knapsack of the 5,898 proof.

    python gen_arith7.py CAPS [OUT]

CAPS: the chain caps (line "0: M(0) .. M(78)").  B(W), W = 0 .. 84, is the largest sum of M(x) - x - 5 over
multisets of x <= 78 with sum (x + 6) <= W (0 for the empty one).  Nothing here is trusted: `K7/Arith.lean`
checks the certificate against the caps with `decide +kernel` (B_closure, B_mono, B_tight, B_eq).
The script also checks what Arith.lean will prove: B(84) <= 50, and the x with M(x) - x - 5 + B(78 - x) >= 50
are 14, 16, 26, 34, 36 with M = 31, 34, 50, 63, 66 there (the five profiles of 5,899).
"""
import os
import sys

TIGHT = {14: 31, 16: 34, 26: 50, 34: 63, 36: 66}
CAPS = sys.argv[1]
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    M = None
    for line in open(CAPS):
        if line.startswith('0:'):
            M = [int(t) for t in line[2:].split()]
    assert M is not None and len(M) == 79
    B = [0] * 85
    for W in range(85):
        best = B[W - 1] if W else 0
        for x in range(0, min(78, W - 6) + 1):
            best = max(best, M[x] - x - 5 + B[W - x - 6])
        B[W] = best
    assert min(B) >= 0 and B[84] <= 50, B[84]
    tight = [x for x in range(79) if 55 + x <= M[x] + B[78 - x]]
    assert set(tight) <= set(TIGHT) and all(M[x] == TIGHT[x] for x in tight), tight
    assert all(M[x] + B[78 - x] == 55 + x for x in TIGHT), 'B_eq'
    L = ['/-! The certificate of the knapsack of the 5,898 proof (generated by `tools/gen_arith7.py`; see there). -/',
         '', 'namespace K7', '',
         '/-- `B W`: the largest value of a family of chains within the weight `W`, for the caps `W5898`. -/',
         'def Btab8 : List Nat := [' + ', '.join(map(str, B)) + ']', '', 'end K7', '']
    with open(os.path.join(OUT, 'K7', 'ArithTab.lean'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L))
    print('B(84) =', B[84], 'tight', tight)


main()
