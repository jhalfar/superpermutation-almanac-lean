"""Write the statement files of the Theorem C batch (2026-11-10).

usage: python -I mkstmt.py WORKTREE NAME [NAME ...]      NAME = C<k>_<cn>_<bn>_<q>, generated in WORKTREE/LowerBounds/SGen

Writes LowerBounds/SCertTune.lean (window statements and model statements), LowerBounds/SFinalTune.lean (the
bounds for Covers), LowerLinks.lean (the Almanac templates) and AlmanacSolution.lean.  The numbers A, q2, C1, C2 and
the fuel are read from the generated assembly file; the bound is Theorem C's closed form, checked by `decide`.
"""
import os
import re
import sys
from math import factorial

WORDS = {9: 'nine', 10: 'ten', 11: 'eleven', 12: 'twelve', 13: 'thirteen', 14: 'fourteen'}


def boundC(k, cn, bn, q):
    hpv = factorial(k) + factorial(k - 1) + factorial(k - 2) + k - 3
    pi = q * (k * k - 4 * k + 1) - cn * (k - 1)
    num = 2 * q * factorial(k - 2) - (2 * q * (k - 2) + bn)
    return hpv + (num + pi - 1) // pi


def fmt(n):
    return f'{n:,}'


def main():
    wt = sys.argv[1]
    names = sys.argv[2:]
    certs = []
    for name in names:
        k, cn, bn, q = (int(x) for x in name[1:].split('_'))
        asm = open(os.path.join(wt, 'LowerBounds', 'SGen', name + '.lean'), encoding='utf-8').read()
        m = re.search(r'theorem search_' + name + r' : S\.search (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) = false', asm)
        assert m, name
        kk, A, q2, C1, C2, bb, fuel = (int(x) for x in m.groups())
        assert (kk, bb) == (k, bn)
        assert A == q * (k - 3) - cn and q2 == 2 * q and C1 == 2 * q * (k - 4) and C2 == 2 * q * (k - 3)
        m2 = re.search(r'kernel in (\d+) parts', asm)
        N = boundC(k, cn, bn, q)
        certs.append(dict(name=name, k=k, cn=cn, bn=bn, q=q, A=A, q2=q2, C1=C1, C2=C2, fuel=fuel, N=N))

    w = ['/-',
         'Generated by tools/mkstmt.py.  Do not edit.',
         '-/',
         'import LowerBounds.SSound',
         'import LowerBounds.SRun',
         'import LowerBounds.SModel']
    w += [f'import LowerBounds.SGen.{c["name"]}' for c in certs]
    w += ['',
          '/-!',
          '# Certificates of Theorem C for this batch',
          '',
          'Each window statement is `S.wstatement_of_search` applied to a search that the kernel has evaluated in parts',
          '(`LowerBounds/SGen/`) and to the run check (`SRun.lean`); each model statement follows by',
          '`modelStatement_of_wstatement` (`SModel.lean`).  No `native_decide`.',
          '-/',
          '',
          'namespace SuperpermLowerBounds',
          '']
    for c in certs:
        t = f'{c["k"]}_{c["cn"]}_{c["bn"]}_{c["q"]}'
        w += [f'/-- `c = {c["cn"]}/{c["q"]}`, `b = {c["bn"]}/{c["q"]}` on {c["k"]} symbols.',
              f'Through Theorem C this gives the bound {fmt(c["N"])}. -/',
              f'theorem wstatement_{t} : S.WStatement {c["k"]} {c["cn"]} {c["bn"]} {c["q"]} :=',
              f'  S.wstatement_of_search (A := {c["A"]}) (q2 := {c["q2"]}) (C1 := {c["C1"]}) (C2 := {c["C2"]}) '
              f'(fuel := {c["fuel"]})',
              '    (by decide) (by decide) (by decide) (by decide) (by decide) (by decide) (by decide)',
              f'    S.runSearch_{c["k"]} SGen.search_{c["name"]}',
              '',
              f'theorem modelStatement_{t} : ModelStatement {c["k"]} {c["cn"]} {c["bn"]} {c["q"]} :=',
              f'  modelStatement_of_wstatement wstatement_{t}',
              '']
    w += ['end SuperpermLowerBounds', '']
    open(os.path.join(wt, 'LowerBounds', 'SCertTune.lean'), 'w', encoding='utf-8', newline='\n').write('\n'.join(w))

    f = ['/-',
         'Generated by tools/mkstmt.py.  Do not edit.',
         '-/',
         'import LowerBounds.SBridgeTheoremC',
         'import LowerBounds.SCertTune',
         '',
         '/-!',
         '# Lower bounds from Theorem C for this batch, without a hypothesis',
         '',
         'For each certificate of `SCertTune.lean`: the three conditions of Theorem C, the value of `boundC`, and',
         '`covers_length_ge_N : ∀ w : List (Fin k), Covers w → N ≤ w.length`, from',
         '`covers_length_ge_boundC_of_model` (`SBridgeTheoremC.lean`).  No `native_decide`.',
         '-/',
         '',
         'namespace SuperpermLowerBounds',
         '',
         'open Hunter PreimageChain SuperpermutationBounds',
         '']
    for c in certs:
        t = f'{c["k"]}_{c["cn"]}_{c["bn"]}_{c["q"]}'
        f += [f'/-! ### {c["k"]} symbols: {fmt(c["N"])} (`c = {c["cn"]}/{c["q"]}`, `b = {c["bn"]}/{c["q"]}`) -/',
              '',
              f'theorem conditionsC_{t} : ConditionsC {c["k"]} {c["cn"]} {c["bn"]} {c["q"]} := '
              '⟨by decide, by decide, by decide, by decide⟩',
              '',
              f'theorem boundC_{t} : boundC {c["k"]} {c["cn"]} {c["bn"]} {c["q"]} = {c["N"]} := by decide',
              '',
              f'/-- Every word over {c["k"]} symbols that contains every permutation of the symbols as a factor has at',
              f'least {fmt(c["N"])} letters. -/',
              f'theorem covers_length_ge_{c["N"]} : ∀ w : List (Fin {c["k"]}), Covers w → {c["N"]} ≤ w.length :=',
              f'  boundC_{t} ▸ covers_length_ge_boundC_of_model (by decide) conditionsC_{t} modelStatement_{t}',
              '']
    f += ['end SuperpermLowerBounds', '']
    open(os.path.join(wt, 'LowerBounds', 'SFinalTune.lean'), 'w', encoding='utf-8', newline='\n').write('\n'.join(f))

    l = ['import AlmanacDefs',
         'import LowerBounds.SFinalTune',
         '',
         '/-!',
         '# Linking lemmas: the Almanac templates from the theorems of `LowerBounds.SFinalTune`',
         '',
         'The development states its bounds with Pantone\'s `SuperpermutationBounds.Covers` (`Challenge.lean` of',
         'github.com/jaypantone/superperm-upper-43-80). A word is a `List (Fin n)` in both vocabularies and its length',
         'is `List.length` in both. This file proves that the two notions of superpermutation agree',
         '(`covers_iff_isSuperpermutation`) and then the templates:',
         '']
    for c in certs:
        l.append(f'* `lower_{WORDS[c["k"]]} : Almanac.LowerBoundAt {c["k"]} {c["N"]}`, from '
                 f'`SuperpermLowerBounds.covers_length_ge_{c["N"]}`.')
    l += ['',
          'These theorems are checked by the kernel; they use no `native_decide`.',
          '-/',
          '',
          'namespace LowerLinks',
          '',
          '/-- Pantone\'s `Covers` is the Almanac\'s `IsSuperpermutation`. -/',
          'theorem covers_iff_isSuperpermutation {n : Nat} (w : List (Fin n)) :',
          '    SuperpermutationBounds.Covers w ↔ Almanac.IsSuperpermutation n w := by',
          '  constructor',
          '  · intro h p hnd hlen',
          '    obtain ⟨u, v, huv⟩ := h p hlen hnd',
          '    show ∃ s t, s ++ p ++ t = w',
          '    exact ⟨u, v, huv.symm⟩',
          '  · intro h p hlen hnd',
          '    obtain ⟨u, v, huv⟩ : ∃ s t, s ++ p ++ t = w := h p hnd hlen',
          '    exact ⟨u, v, huv.symm⟩',
          '']
    for c in certs:
        l += [f'/-- **Every superpermutation on {c["k"]} symbols has at least {fmt(c["N"])} letters**, as the Almanac '
              'template. -/',
              f'theorem lower_{WORDS[c["k"]]} : Almanac.LowerBoundAt {c["k"]} {c["N"]} := fun w hw =>',
              f'  SuperpermLowerBounds.covers_length_ge_{c["N"]} w ((covers_iff_isSuperpermutation w).mpr hw)',
              '']
    l += ['end LowerLinks', '']
    open(os.path.join(wt, 'LowerLinks.lean'), 'w', encoding='utf-8', newline='\n').write('\n'.join(l))

    s = ['-- Lower bounds from Theorem C (proofs/lean/lower of github.com/jhalfar/superpermutations) with re-tuned',
         '-- constants; every finite search is evaluated by the kernel. The linking lemmas are in LowerLinks.lean.',
         'import AlmanacDefs',
         'import LowerLinks',
         '',
         'namespace AlmanacSubmission',
         '']
    for c in certs:
        s += [f'/-- Every superpermutation on {c["k"]} symbols has length at least {fmt(c["N"])}. -/',
              f'theorem lower_{WORDS[c["k"]]} : Almanac.LowerBoundAt {c["k"]} {c["N"]} := '
              f'LowerLinks.lower_{WORDS[c["k"]]}',
              '']
    s += ['end AlmanacSubmission', '']
    open(os.path.join(wt, 'AlmanacSolution.lean'), 'w', encoding='utf-8', newline='\n').write('\n'.join(s))
    for c in certs:
        print(c['name'], c['N'], 'fuel', c['fuel'])


if __name__ == '__main__':
    main()
